"""
Regenerate tests/data/cf_canonical_units_written.tsv: how pint-cf writes back
every canonical unit of the CF standard name table, with the "cf" and "~cf"
formats.

CF 1.13 section 3.1 requires a units string "that can be recognized by the
UDUNITS package", so each written string is also checked against the
UDUNITS-2 C library through cf_units (dev dependency group). The tests only
compare against the file, so review the diff and the reported strings before
committing it.

Run it after changing the formatter or updating
tests/data/cf_standard_name_canonical_units.txt:

    uv run python tools/write_canonical_units.py
"""

import sys
from pathlib import Path

import cf_units

from pint_cf import cf_unitregistry

DATA = Path(__file__).parent.parent / "tests" / "data"
SOURCE = DATA / "cf_standard_name_canonical_units.txt"
TARGET = DATA / "cf_canonical_units_written.tsv"

HEADER = """\
# How pint-cf writes back each readable canonical unit of
# cf_standard_name_canonical_units.txt: units, then the "cf" and "~cf"
# formats, tab-separated. Every written string was checked against the
# UDUNITS-2 C library (through cf_units) unless listed in
# test_cf_conformance.py as a known failure.
# Generated by tools/write_canonical_units.py - don't edit by hand.
"""


def main() -> int:
    ureg = cf_unitregistry()
    lines = [
        line
        for line in SOURCE.read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    ]

    rows = []
    for units in lines:
        try:
            unit = ureg.Unit(units)
        except Exception as error:
            print(f"unreadable, skipped: {units!r} ({type(error).__name__})")
            continue
        rows.append((units, format(unit, "cf"), format(unit, "~cf")))

    invalid = []
    for row in rows:
        for written in row[1:]:
            try:
                cf_units.Unit(written)
            except ValueError:
                invalid.append(written)
    for written in invalid:
        print(f"not recognized by UDUNITS-2: {written!r}")

    TARGET.write_text(
        HEADER + "".join("\t".join(row) + "\n" for row in rows), encoding="utf-8"
    )
    print(f"wrote {len(rows)} units to {TARGET}")
    return 1 if invalid else 0


if __name__ == "__main__":
    sys.exit(main())
