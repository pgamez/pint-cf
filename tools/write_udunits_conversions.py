"""
Regenerate tests/data/udunits_conversions.tsv: conversions computed by the
UDUNITS-2 C library (through cf_units, dev dependency group), which
pint-cf's plain UDUNITS-2 registry (cf_extensions=False) must reproduce
when reading a CF units string without CFContext - i.e. with
units_metadata absent, which CF 1.13 section 3.1.2 says to read as
"temperature: unknown", where pint-cf follows UDUNITS. The CF extensions
(psu, Sv as sverdrup) differ from UDUNITS on purpose and are tested apart.

Mostly temperatures - bare units (on-scale for UDUNITS) and compound ones
(a difference) - plus a few common CF units. A pair UDUNITS refuses to
convert is stored as "not convertible".

Each case is checked against pint-cf too, and differences are reported:
review them and the diff before committing the file. Run it after editing
CASES:

    uv run python tools/write_udunits_conversions.py
"""

import sys
from pathlib import Path

import cf_units
import pint

from pint_cf import cf_unitregistry

TARGET = Path(__file__).parent.parent / "tests" / "data" / "udunits_conversions.tsv"

NOT_CONVERTIBLE = "not convertible"

# (value, units, target)
CASES = [
    # Bare temperature units: on-scale.
    (15, "degC", "K"),
    (15, "degC", "degF"),
    (288.15, "K", "degC"),
    (59, "degF", "degC"),
    (59, "degF", "K"),
    (500, "degR", "K"),
    (500, "degR", "degF"),
    (15, "degrees_C", "K"),
    (15, "degree_Celsius", "K"),
    (15, "celsius", "kelvin"),
    (59, "fahrenheit", "degree_C"),
    (-40, "degC", "degF"),
    (0, "K", "degC"),
    # Prefixed kelvin has no offset.
    (1500, "mK", "K"),
    # Compound temperature units: a difference, scale factor only.
    (2, "degC/s", "K/s"),
    (2, "degC/s", "mK/s"),
    (0.02, "degC/year", "degF/year"),
    (1, "degC/day", "K/s"),
    (1.8, "degF/day", "degC/day"),
    (1, "K/s", "degC/s"),
    (3, "degC m-2", "K m-2"),
    (10, "kg degC m-2", "g K m-2"),
    (5, "W m-2 degC-1", "W m-2 K-1"),
    (5, "W m-2 degF-1", "W m-2 K-1"),
    (2, "degC-1", "K-1"),
    (1, "degF2", "K2"),
    (4, "degC2", "K2"),
    (1, "degC m s-1", "K m s-1"),
    (1, "J kg-1 degC-1", "J kg-1 K-1"),
    # An integer glued to a closing parenthesis is an exponent.
    (1, "(m-1)-1", "m"),
    (1, "(m s)-1", "m-1 s-1"),
    (1, "(m)2", "m2"),
    (1, "((m)2)3", "m6"),
    (1, "W m-2 sr-1 (m-1)-1", "W m-1 sr-1"),
    (2, "(degC s)-1", "K-1 s-1"),
    # Not temperatures at all: C is the coulomb, F the farad.
    (1, "K/s", "C/s"),
    (1, "degC", "C"),
    (1, "K", "F"),
    # Common CF units. psu and Sv (sievert in UDUNITS) are here to check
    # the registry without CF extensions matches UDUNITS.
    (1013.25, "hPa", "Pa"),
    (1, "atm", "hPa"),
    (1, "kg m-2 s-1", "mm/day"),
    (1, "kg m-2", "g m-2"),
    (10, "m s-1", "km/h"),
    (1, "knot", "m s-1"),
    (1, "day", "s"),
    (50, "%", "1"),
    (1, "ppm", "1"),
    (35, "psu", "1"),
    (1, "Sv", "m3 s-1"),
    (90, "degrees_north", "radian"),
]

HEADER = """\
# Conversions computed by the UDUNITS-2 C library (through cf_units):
# value, units, target, then the converted value or "not convertible",
# tab-separated. pint-cf must give the same result reading the units with
# ureg.Quantity(value, units), no CFContext, and cf_extensions=False.
# Generated by tools/write_udunits_conversions.py - don't edit by hand.
"""


def udunits(value: float, units: str, target: str) -> str:
    try:
        return repr(float(cf_units.Unit(units).convert(value, cf_units.Unit(target))))
    except ValueError:
        return NOT_CONVERTIBLE


def pint_cf(ureg: pint.UnitRegistry, value: float, units: str, target: str) -> str:
    try:
        return repr(float(ureg.Quantity(value, units).to(target).magnitude))
    except Exception as error:  # reported, not raised
        return f"{NOT_CONVERTIBLE} ({type(error).__name__})"


def main() -> int:
    ureg = cf_unitregistry(cf_extensions=False)
    rows = []
    differences = 0
    for value, units, target in CASES:
        expected = udunits(value, units, target)
        rows.append((repr(value), units, target, expected))
        got = pint_cf(ureg, value, units, target)
        same = (
            got.startswith(NOT_CONVERTIBLE)
            if expected == NOT_CONVERTIBLE
            else not got.startswith(NOT_CONVERTIBLE)
            and abs(float(got) - float(expected)) <= 1e-9 * max(1, abs(float(expected)))
        )
        if not same:
            differences += 1
            print(
                f"differs: {value} {units} -> {target}: "
                f"UDUNITS {expected}, pint-cf {got}"
            )

    TARGET.write_text(
        HEADER + "".join("\t".join(row) + "\n" for row in rows), encoding="utf-8"
    )
    print(f"wrote {len(rows)} conversions to {TARGET}")
    return 1 if differences else 0


if __name__ == "__main__":
    sys.exit(main())
